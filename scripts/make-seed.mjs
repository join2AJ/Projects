// Builds supabase/seed/tailbone.sql from the Tailbone audit module, so the database matches the audit exactly.
// Run: node scripts/make-seed.mjs
import { build } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";

const out = "node_modules/.cache/seed-audit.mjs";
await build({
  entryPoints: ["src/projects/tailbone/audit.jsx"], bundle: true, platform: "node", format: "esm",
  outfile: out, jsx: "automatic", external: ["react", "react/jsx-runtime", "recharts"], logLevel: "error",
});
const A = await import("../" + out);

const q = (v) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const SEV = { Critical: "critical", High: "high", Medium: "medium", Low: "low" };
const ST = {
  Contained: "in_progress", Open: "open", Done: "resolved", Fixed: "resolved",
  "Before launch": "waiting_client", Superseded: "superseded", "In progress": "in_progress",
};
const P = "(select id from public.projects where slug = 'tailbone-treatment')";

const issues = A.ISSUES.map((i, k) => {
  const [st, now] = A.ISSUE_STATUS[k];
  const owner = st === "Before launch" || k === 3 ? "client" : "me";
  return `(${P}, ${q(i.t)}, ${q(SEV[i.sl])}, ${q(ST[st])}, ${q(i.ev)}, ${q(i.fix)}, ${q(now)}, ${q(owner)}, '2026-10-18', ${
    ST[st] === "resolved" || ST[st] === "superseded" ? "'2026-10-18'" : "null"}, ${k})`;
});

// Monthly Google Ads invoices incl. GST, Jan 2021 → Sep 2026
const spend = A.ALL.map((v, k) => {
  const y = 2021 + Math.floor(k / 12), m = (k % 12) + 1;
  return `(${P}, 'Google Ads cost incl. GST', '${y}-${String(m).padStart(2, "0")}-01', ${v}, '₹', 'Google Ads invoices')`;
});

